/**
 * Deterministic pseudo-random helpers.
 *
 * Every generated item is reproducible from its seed: the same trial set and
 * seed must yield the same options in the same order.
 */

export function hashSeed(input) {
  let h = 2166136261;
  const text = String(input);
  for (let i = 0; i < text.length; i += 1) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function makeRng(...parts) {
  return mulberry32(hashSeed(parts.join('|')));
}

/** Fisher-Yates with an injected rng; returns a new array. */
export function shuffle(list, rng) {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

export function pickOne(list, rng) {
  if (!list.length) return undefined;
  return list[Math.floor(rng() * list.length)];
}
